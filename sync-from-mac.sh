#!/usr/bin/env bash
# Mirror the Mac's personal agent config into this repo and push, so Conductor
# cloud workspaces pick the changes up on their next session start:
#   ~/.claude/{commands,agents,skills,workflows}  -> <dir>/
#     (after writing ~/.claude/commands/<plugin>-<skill>.md stubs for $MENU_PLUGINS)
#   ~/.agent-shared/docs/<$SHARED_DOCS>.md         -> agent-shared/docs/
#   ~/.agent-shared/wiki/SCHEMA.md                 -> agent-shared/wiki/
#
# Only tooling ships: no wiki pages, no per-repo iterate configs. home/CLAUDE.md is
# edited here, not mirrored: the Mac's ~/.claude/CLAUDE.md carries org-specific lines.
# Before committing, the tree is checked against the regexes in .sync-deny
# (gitignored, one per line); any match aborts the sync.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC="${CLAUDE_SOURCE_DIR:-$HOME/.claude}"
SHARED="${AGENT_SHARED_DIR:-$HOME/.agent-shared}"

# Keep in sync with install.sh.
DIRS="commands agents skills workflows"

# The ~/.agent-shared/docs files that commands, skills and agents read.
SHARED_DOCS="global-engineering merge-workflow conduct-map-workflow changeset-report-workflow synthesize-learnings spec-workflow refactor-workflow implement-plan-workflow review-workflow beads-issue-tracker pstack-models"

# Plugins whose skills get a /<plugin>-<skill> command file, so they show up in
# Conductor's slash menu (it lists command files, not plugin skills).
MENU_PLUGINS="pstack@pstack-claude"
STUB_MARKER="<!-- generated by local-agent-commands/sync-from-mac.sh; edits are overwritten -->"

# Write $SRC/commands/<plugin>-<skill>.md for each user-invocable skill of the
# installed plugin. Stubs from earlier runs are removed first, so skills (or
# plugins) that went away lose their stub. Files without the marker are never touched.
generate_plugin_command_stubs() {
  local registry="$SRC/plugins/installed_plugins.json" id plugin path skill_md name frontmatter desc count
  mkdir -p "$SRC/commands"
  { grep -lxF "$STUB_MARKER" "$SRC/commands"/*.md 2>/dev/null || true; } | while IFS= read -r f; do rm -f "$f"; done
  command -v jq >/dev/null 2>&1 || { echo "sync-from-mac: jq missing; skipping plugin command stubs" >&2; return 0; }
  [ -f "$registry" ] || return 0
  for id in $MENU_PLUGINS; do
    plugin="${id%@*}"
    path="$(jq -r --arg id "$id" '.plugins[$id][0].installPath // empty' "$registry")"
    [ -d "$path/skills" ] || { echo "sync-from-mac: $id not installed; no stubs" >&2; continue; }
    count=0
    for skill_md in "$path"/skills/*/SKILL.md; do
      [ -f "$skill_md" ] || continue
      name="$(basename "$(dirname "$skill_md")")"
      # Read only the frontmatter block between the first two --- lines.
      frontmatter="$(awk 'NR==1 && $0=="---" {fm=1; next} fm && $0=="---" {exit} fm' "$skill_md")"
      # Skills hidden from users, or that the model may not invoke, can't be stubbed.
      printf '%s\n' "$frontmatter" | grep -qE '^(user-invocable: *false|disable-model-invocation: *true)' && continue
      desc="$(printf '%s\n' "$frontmatter" | grep -m1 '^description:' || true)"
      [ -n "$desc" ] || desc="description: $plugin $name skill"
      # disable-model-invocation keeps the stub out of the model's skill list, where
      # it would duplicate the plugin skill it points at.
      cat > "$SRC/commands/$plugin-$name.md" <<EOF
---
$desc
disable-model-invocation: true
---
$STUB_MARKER
Invoke the \`$plugin:$name\` skill with the Skill tool and follow its instructions. Arguments: \$ARGUMENTS
EOF
      count=$((count + 1))
    done
    echo "sync-from-mac: $count command stub(s) for $id"
  done
}

cd "$REPO"
git pull --quiet --rebase 2>/dev/null || true

generate_plugin_command_stubs

# Copy with -L so symlinked entries (e.g. skills/lavish -> ~/.agents/skills/lavish)
# are materialized as real files. A plain -R would commit the symlink itself, whose
# target does not exist inside a Linux cloud sandbox.
# Stage first, then swap, so a failed copy can't leave the repo dir empty.
for dir in $DIRS; do
  [ -d "$SRC/$dir" ] || continue
  staging="$(mktemp -d)"
  cp -RL "$SRC/$dir/." "$staging/"
  rm -rf "${REPO:?}/$dir"
  mkdir -p "$REPO/$dir"
  cp -R "$staging/." "$REPO/$dir/"
  rm -rf "$staging"
done

# iterate's per-repo configs name private repos and their setup; keep only the README.
find "$REPO/skills/iterate/repos" -mindepth 1 ! -name README.md -exec rm -rf {} + 2>/dev/null || true

rm -rf "${REPO:?}/agent-shared"
mkdir -p "$REPO/agent-shared/docs" "$REPO/agent-shared/wiki"
for doc in $SHARED_DOCS; do
  cp -L "$SHARED/docs/$doc.md" "$REPO/agent-shared/docs/"
done
cp -L "$SHARED/wiki/SCHEMA.md" "$REPO/agent-shared/wiki/"

find "$REPO" \( -name '._*' -o -name '.DS_Store' \) -delete 2>/dev/null || true

if [ -z "$(git status --porcelain)" ]; then
  echo "sync-from-mac: no changes"
  exit 0
fi

# grep exits 2 on a missing path even when it matched, so pass only dirs that exist.
synced="$(for d in $DIRS agent-shared home; do [ -d "$d" ] && echo "$d"; done)"
if [ -s "$REPO/.sync-deny" ] && grep -rIinE -f "$REPO/.sync-deny" $synced; then
  echo "sync-from-mac: the lines above match .sync-deny; scrub them on the Mac and rerun. Nothing committed." >&2
  exit 1
fi

echo "sync-from-mac: changes detected"
git status --short | head -40
git add -A
git commit -qm "sync from Mac: $(date '+%Y-%m-%d %H:%M')"
git push --quiet
echo "sync-from-mac: pushed"
